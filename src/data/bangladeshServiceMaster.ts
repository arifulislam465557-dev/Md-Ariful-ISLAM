export function resolveItemDepartment(
  item: {
    departmentId?: ServiceDepartmentId;
    category?: string;
    subcategory?: string;
    code?: string;
    name?: string;
    testName?: string;
  }
): ServiceDepartmentId {
  if (item.departmentId && SERVICE_DEPARTMENTS[item.departmentId]) {
    return item.departmentId;
  }

  const cat = String(item.category || '').toLowerCase();
  const sub = String(item.subcategory || '').toLowerCase();
  const code = String(item.code || '').toLowerCase();
  const name = String(item.name || item.testName || '').toLowerCase();

  if (
    cat.includes('x-ray') ||
    cat.includes('xray') ||
    cat === 'radiology' ||
    sub.includes('x-ray') ||
    code.startsWith('xr-') ||
    name.includes('x-ray') ||
    name.includes('xray')
  ) {
    return 'xray';
  }

  if (
    cat.includes('ultrasound') ||
    cat.includes('usg') ||
    cat.includes('doppler') ||
    sub.includes('usg') ||
    sub.includes('doppler') ||
    code.startsWith('usg-') ||
    code.startsWith('dop-') ||
    name.includes('ultrasound') ||
    name.includes('usg') ||
    name.includes('doppler')
  ) {
    return 'ultrasound';
  }

  if (
    cat.includes('ecg') ||
    cat.includes('cardiology') ||
    cat.includes('diagnostic') ||
    sub.includes('ecg') ||
    sub.includes('echo') ||
    code.startsWith('ecg-') ||
    code.startsWith('crd-') ||
    name.includes('ecg') ||
    name.includes('echocardiogram') ||
    name.includes('2d echo') ||
    name.includes('holter') ||
    name.includes('tmt') ||
    name.includes('spirometry') ||
    name.includes('eeg')
  ) {
    return 'ecg';
  }

  if (
    cat.includes('doctor') ||
    cat.includes('consultation') ||
    cat.includes('opd') ||
    code.startsWith('doc-') ||
    code.startsWith('opd-') ||
    name.includes('consultation') ||
    name.includes('doctor visit')
  ) {
    return 'doctorVisit';
  }

  if (
    cat.includes('pharmacy') ||
    cat.includes('medicine') ||
    code.startsWith('phm-') ||
    sub.includes('pharmacy')
  ) {
    return 'pharmacy';
  }

  if (
    cat.includes('other') ||
    cat.includes('procedure') ||
    cat.includes('registration') ||
    cat.includes('admission') ||
    code.startsWith('srv-') ||
    code.startsWith('reg-') ||
    code.startsWith('bed-')
  ) {
    return 'other';
  }

  return 'pathology';
}

export function getDepartmentLabel(deptId: ServiceDepartmentId, language: 'bn' | 'en' = 'en'): string {
  const meta = SERVICE_DEPARTMENTS[deptId] || SERVICE_DEPARTMENTS.pathology;
  return language === 'bn' ? meta.labelBn : meta.labelEn;
}

