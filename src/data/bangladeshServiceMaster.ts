/**
 * Merges the existing LabTest catalog with our comprehensive Bangladesh Service Master
 * AND dynamically generates/updates Doctor Consultation items from the live Doctor Master (`doctors`),
 * ensuring every doctor's real fee (`doc.fee`) is available in the Billing Master without duplicating codes.
 */
export function mergeServiceCatalogWithDoctors(
  existingTests: LabTest[],
  doctors: Doctor[]
): LabTest[] {
  const byCode = new Map<string, LabTest>();

  // 1. Seed existing tests first (with resolved departmentId)
  for (const t of existingTests) {
    const normalizedCode = String(t.code || t.id).trim().toUpperCase();
    byCode.set(normalizedCode, {
      ...t,
      code: normalizedCode,
      departmentId: resolveItemDepartment(t),
      discountEligible: t.discountEligible !== false,
      priceVerified: t.priceVerified ?? t.rangeVerified ?? true,
      isActive: t.isActive !== false,
    });
  }

  // 2. Add missing items from BANGLADESH_COMPREHENSIVE_SERVICE_CATALOG
  for (const item of BANGLADESH_COMPREHENSIVE_SERVICE_CATALOG) {
    const normalizedCode = item.code.trim().toUpperCase();
    const existing = byCode.get(normalizedCode);
    if (!existing) {
      byCode.set(normalizedCode, { ...item, code: normalizedCode });
    } else {
      // Enrich missing metadata (Bangla name, departmentId, subcategory) without overwriting custom user price
      byCode.set(normalizedCode, {
        ...existing,
        nameBn: existing.nameBn || item.nameBn,
        subcategory: existing.subcategory || item.subcategory,
        departmentId: existing.departmentId || item.departmentId,
        synonyms: existing.synonyms || item.synonyms,
        discountEligible: existing.discountEligible ?? item.discountEligible,
        maxDiscountPercent: existing.maxDiscountPercent ?? item.maxDiscountPercent,
      });
    }
  }

  // 3. Dynamically synchronize each active Doctor from Doctor Master as a direct consultation item
  for (const doc of doctors) {
    if (!doc || !doc.name || doc.code === 'SELF') continue;
    const docServiceCode = `DOC-${String(doc.code || doc.id).trim().toUpperCase()}`;
    const existingDocItem = byCode.get(docServiceCode);
    const fee = Number(doc.fee) > 0 ? Number(doc.fee) : 500;

    byCode.set(docServiceCode, {
      id: existingDocItem?.id || `doc_srv_${doc.id}`,
      code: docServiceCode,
      name: `Consultation — ${doc.name} (${doc.specialty || 'Specialist'})`,
      nameBn: `ডাক্তার ভিজিট — ${doc.name} (${doc.specialty || 'বিশেষজ্ঞ'})`,
      category: 'Doctor Consultation',
      subcategory: doc.specialty || 'Consultant Chamber',
      departmentId: 'doctorVisit',
      doctorId: doc.id,
      unit: `Room ${doc.roomNo || 'OPD'}`,
      normalRange: doc.degree || 'Consultation',
      price: fee,
      costPrice: 0,
      discountEligible: true,
      maxDiscountPercent: 25,
      priceVerified: true,
      sampleType: 'OPD Consultation',
      method: `Room ${doc.roomNo || 'OPD'}`,
      turnaroundTime: 'Same Day',
      isActive: existingDocItem ? existingDocItem.isActive !== false : true,
      synonyms: [doc.name.toLowerCase(), String(doc.code || '').toLowerCase(), String(doc.specialty || '').toLowerCase(), 'doctor visit'],
    });
  }

  return Array.from(byCode.values());
}

export function exportServiceMasterToCsv(tests: LabTest[]): string {
  const headers = [
    'Code',
    'Name (English)',
    'Name (Bangla)',
    'Category',
    'Subcategory',
    'DepartmentID',
    'Price (BDT)',
    'CostPrice (BDT)',
    'DiscountEligible',
    'MaxDiscountPercent',
    'SampleType',
    'TurnaroundTime',
    'PriceVerified',
    'IsActive',
  ];

  const escapeCsv = (val: any) => {
    const str = String(val ?? '');
    if (str.includes(',') || str.includes('"') || str.includes('\n')) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return str;
  };

  const rows = tests.map((t) =>
    [
      t.code,
      t.name,
      t.nameBn || '',
      t.category,
      t.subcategory || '',
      resolveItemDepartment(t),
      t.price,
      t.costPrice || 0,
      t.discountEligible !== false ? 'YES' : 'NO',
      t.maxDiscountPercent ?? 25,
      t.sampleType || '',
      t.turnaroundTime || '',
      t.priceVerified ? 'VERIFIED' : 'SEED',
      t.isActive !== false ? 'ACTIVE' : 'INACTIVE',
    ]
      .map(escapeCsv)
      .join(',')
  );

  return [headers.join(','), ...rows].join('\n');
}

export function parseServiceMasterCsv(csvText: string): Partial<LabTest>[] {
  const lines = csvText
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter(Boolean);
  if (lines.length < 2) return [];

  const splitCsvLine = (line: string): string[] => {
    const result: string[] = [];
    let current = '';
    let inQuotes = false;
    for (let i = 0; i < line.length; i++) {
      const ch = line[i];
      if (ch === '"') {
        if (inQuotes && line[i + 1] === '"') {
          current += '"';
          i++;
        } else {
          inQuotes = !inQuotes;
        }
      } else if (ch === ',' && !inQuotes) {
        result.push(current.trim());
        current = '';
      } else {
        current += ch;
      }
    }
    result.push(current.trim());
    return result;
  };

  const parsed: Partial<LabTest>[] = [];
  for (let i = 1; i < lines.length; i++) {
    const cols = splitCsvLine(lines[i]);
    if (cols.length < 7) continue;
    const [
      code,
      name,
      nameBn,
      category,
      subcategory,
      deptRaw,
      priceRaw,
      costRaw,
      discEligRaw,
      maxDiscRaw,
      sampleType,
      turnaroundTime,
      verifiedRaw,
      activeRaw,
    ] = cols;

    if (!code || !name) continue;
    const price = Number(priceRaw);
    if (!Number.isFinite(price) || price < 0) continue;

    const deptCandidate = (deptRaw || '').toLowerCase() as ServiceDepartmentId;
    const departmentId: ServiceDepartmentId = SERVICE_DEPARTMENTS[deptCandidate]
      ? deptCandidate
      : resolveItemDepartment({ code, name, category, subcategory });

    parsed.push({
      code: code.toUpperCase(),
      name,
      nameBn: nameBn || undefined,
      category: category || 'Biochemistry',
      subcategory: subcategory || undefined,
      departmentId,
      price,
      costPrice: Number(costRaw) || 0,
      discountEligible: String(discEligRaw || 'YES').toUpperCase() !== 'NO',
      maxDiscountPercent: Number(maxDiscRaw) || 25,
      sampleType: sampleType || 'Serum',
      turnaroundTime: turnaroundTime || 'Same Day',
      priceVerified: String(verifiedRaw || '').toUpperCase() === 'VERIFIED',
      isActive: String(activeRaw || 'ACTIVE').toUpperCase() !== 'INACTIVE',
    });
  }
  return parsed;
}
